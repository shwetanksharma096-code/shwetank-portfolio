const KEY = 'shwetank_portfolio_v1';

export function getData(): typeof defaultData {
  if (typeof window === 'undefined') return defaultData;
  try {
    const raw = localStorage.getItem(KEY);
    if (!raw) return defaultData;
    const stored = JSON.parse(raw);
    if (!stored || typeof stored !== 'object') return defaultData;

    return {
      hero: { ...defaultData.hero, ...(stored.hero || {}) },
      heroStats: { ...defaultData.heroStats, ...(stored.heroStats || {}) },
      campaigns: { ...defaultData.campaigns, ...(stored.campaigns || {}) },
      videoProjects: stored.videoProjects ?? defaultData.videoProjects,
      websites: (stored.websites && stored.websites.length > 0) ? stored.websites : defaultData.websites,
      reviews: (stored.reviews && stored.reviews.length > 0) ? stored.reviews : defaultData.reviews,
      experience: stored.experience ?? defaultData.experience,
      about: { ...defaultData.about, ...(stored.about || {}) },
      skills: stored.skills ?? defaultData.skills,
      settings: { ...defaultData.settings, ...(stored.settings || {}) },
      brandLogos: (stored.brandLogos && stored.brandLogos.length > 0) ? stored.brandLogos : defaultData.brandLogos,
      awardLinks: (stored.awardLinks && stored.awardLinks.length > 0) ? stored.awardLinks : defaultData.awardLinks,
      achievements: (stored.achievements && stored.achievements.length > 0) ? stored.achievements : defaultData.achievements,
      services: stored.services ?? defaultData.services,
    };
  } catch (err) {
    console.warn("Store: Falling back to default data due to error:", err);
    return defaultData;
  }
}

export function saveData(data: typeof defaultData): void {
  if (typeof window === 'undefined') return;
  localStorage.setItem(KEY, JSON.stringify(data));
}

export async function fetchGlobalData(): Promise<typeof defaultData | null> {
  try {
    const res = await fetch('/api/read?t=' + Date.now(), { cache: 'no-store' });
    if (!res.ok) return null;
    const data = await res.json();
    if (data && !data.error && Object.keys(data).length > 0) {
      return {
        ...defaultData,
        ...data,
      };
    }
    return null;
  } catch (e) {
    console.error('Failed to fetch global data', e);
    return null;
  }
}

export async function saveGlobalData(data: typeof defaultData): Promise<boolean> {
  try {
    const password = (typeof window !== 'undefined' && sessionStorage.getItem('shwetank_admin_auth')) || 'shwetank@2024';
    const res = await fetch('/api/save', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ password, data })
    });
    const json = await res.json();
    return json.success === true;
  } catch (e) {
    console.error('Failed to save global data', e);
    return false;
  }
}

export function updateSection(section: string, value: any): typeof defaultData {
  const current = getData();
  const updated = { ...current, [section]: value };
  saveData(updated);
  return updated;
}

export function resetData(): typeof defaultData {
  if (typeof window === 'undefined') return defaultData;
  saveData(defaultData);
  return defaultData;
}

export interface Creator {
  creator: string;
  profile: string;
  liveLink: string;
}

export interface GroupedCampaigns {
  [brand: string]: {
    [campaign: string]: Creator[];
  };
}

export function parseCampaignCsv(csvText: string): { grouped: GroupedCampaigns; brands: string[] } {
  const rows: string[][] = [];
  let curRow: string[] = [];
  let curCell = '';
  let inQuotes = false;

  for (let i = 0; i < csvText.length; i++) {
    const char = csvText[i];
    const nextChar = csvText[i + 1];

    if (char === '"' && inQuotes && nextChar === '"') {
      curCell += '"'; i++;
    } else if (char === '"') {
      inQuotes = !inQuotes;
    } else if (char === ',' && !inQuotes) {
      curRow.push(curCell.trim()); curCell = '';
    } else if ((char === '\n' || char === '\r') && !inQuotes) {
      if (char === '\r' && nextChar === '\n') i++;
      curRow.push(curCell.trim());
      if (curRow.length > 1 || curRow[0] !== '') rows.push(curRow);
      curRow = []; curCell = '';
    } else {
      curCell += char;
    }
  }
  if (curCell || curRow.length > 0) {
    curRow.push(curCell.trim());
    rows.push(curRow);
  }

  const headerIdx = rows.findIndex(r => r.some(c => c.toLowerCase().includes('brand') || c.toLowerCase().includes('month')));
  if (headerIdx === -1) return { grouped: {}, brands: [] };

  const dataRows = rows.slice(headerIdx + 1);
  let lastBrand = '', lastCampaign = '';
  const finalData: { brand: string; campaign: string; creator: string; profile: string; liveLink: string }[] = [];

  dataRows.forEach(v => {
    if (!v || v.length < 4) return;
    
    const brandVal    = v[1]?.trim();
    const campaignVal = v[2]?.trim();
    const creator     = v[3]?.trim();
    const profile     = v[4]?.trim();
    const liveLink    = v[5]?.trim();

    if (brandVal && brandVal.length < 40 && !brandVal.startsWith('-')) {
      lastBrand = brandVal;
    }
    
    if (campaignVal && campaignVal.length < 100 && !campaignVal.startsWith('-')) {
      lastCampaign = campaignVal;
    }

    if (creator && lastBrand) {
      finalData.push({ 
        brand: lastBrand, 
        campaign: lastCampaign || 'General', 
        creator, 
        profile, 
        liveLink 
      });
    }
  });

  const grouped: GroupedCampaigns = {};
  finalData.forEach(row => {
    if (!grouped[row.brand]) grouped[row.brand] = {};
    if (!grouped[row.brand][row.campaign]) grouped[row.brand][row.campaign] = [];
    grouped[row.brand][row.campaign].push({
      creator:  row.creator,
      profile:  row.profile,
      liveLink: row.liveLink
    });
  });

  return { grouped, brands: Object.keys(grouped) };
}

export function getYoutubeId(url: string | undefined): string | null {
  if (!url) return null;
  const m = url.match(/(?:youtu\.be\/|youtube\.com\/(?:v\/|u\/\w\/|embed\/|watch\?v=|shorts\/|live\/))([A-Za-z0-9_-]{11})/);
  return m ? m[1] : null;
}

export function getInstagramId(url: string | undefined): string | null {
  if (!url) return null;
  const m = url.match(/instagram\.com\/(?:[a-zA-Z0-9._]+\/)?(?:p|reel|reels|tv)\/([A-Za-z0-9_-]+)/i);
  return m ? m[1] : null;
}

export function getYoutubeThumbnail(url: string | undefined): string | null {
  const id = getYoutubeId(url);
  return id ? `https://img.youtube.com/vi/${id}/hqdefault.jpg` : null;
}

export function getWhatsAppLink(phone: string, message?: string): string {
  const cleanPhone = phone.replace(/\D/g, '');
  const formattedPhone = cleanPhone.length === 10 ? `91${cleanPhone}` : cleanPhone;
  
  const isMobile = typeof window !== 'undefined'
    ? /Android|webOS|iPhone|iPad|iPod|BlackBerry|IEMobile|Opera Mini/i.test(navigator.userAgent)
    : false;

  const base = isMobile ? 'whatsapp://send' : 'https://api.whatsapp.com/send';
  const query = message 
    ? `?phone=${formattedPhone}&text=${encodeURIComponent(message)}` 
    : `?phone=${formattedPhone}`;
  return `${base}${query}`;
}
